/**
 * «Работа системы»: когда соберутся данные и когда начнётся расчёт.
 *
 * Здесь держится правило FR-053, ради которого блок и заведён: **это три
 * разные вещи, и смешивать их нельзя**.
 *
 *  - срок сбора данных завершившейся сессии известен точно — его считает
 *    сервер и отдаёт полем `next_check_at`;
 *  - готовность данных заранее неизвестна — её не обещает никто;
 *  - начало расчёта следует за готовностью, поэтому точного времени начала
 *    здесь нет и не будет (FR-054).
 *
 * **Срок сбора не называется периодичностью проверки.** Ранжирование ищет
 * работу непрерывно: по тику планировщика, после каждого успешного сбора, при
 * запуске и по команде человека. Прежний текст «Следующий цикл системы — 19:30»
 * утверждал обратное — что до этого часа система стоит.
 *
 * **Даты у срока нет, и это не упущение.** `next_check_at` считается часами, без
 * календаря, поэтому в воскресенье называл сегодняшний вечер — а торгов не было
 * и собирать было нечего. Взять «следующую торговую сессию» из календаря нельзя:
 * он эмпирический и знает только прошлое — день становится сессией лишь после
 * того, как за него собраны данные. Поэтому показывается то, что известно
 * точно, — час, — и оговорка о том, что без сессии сбора не будет.
 *
 * Текст правила выводится из состояния, которое посчитал сервер, а не из
 * собственных догадок интерфейса о расписании: расписание приходит одним полем
 * `next_check_at`, и второго источника у экрана нет.
 */

import type { DailyMlStatusDto } from '@/entities/daily-ml';
import { formatClock } from '@/shared/lib/daily-ml-format';
import { stateName } from './DailyMlState';

function startRule(status: DailyMlStatusDto): string {
  if (status.paused) return 'Не запланирован — ранжирование остановлено.';
  if (status.current) {
    return 'Текущий прогон уже идёт. Время начала следующего зависит от готовности данных.';
  }
  if (status.data_gap_sessions > 0) {
    return 'Ранжирование начнётся после восстановления обязательного входа.';
  }
  if (status.status === 'lagging') {
    return 'Обработка начнётся немедленно. Задания выполняются по одному.';
  }
  if (status.status === 'up_to_date') {
    return 'Новый прогон начнётся после готовности данных следующей торговой сессии.';
  }
  return 'Начнётся сразу после готовности данных.';
}

function summary(status: DailyMlStatusDto): string {
  if (status.paused) return 'Авторанжирование остановлено';
  if (status.current) return 'Идёт ранжирование';

  switch (stateName(status)) {
    case 'up_to_date':
      return 'Новых данных нет';
    case 'lagging':
      return 'Обработка накопившихся дат';
    case 'failed':
      return 'Прогон не выполнен';
    case 'data_gap':
      return 'Нужны данные';
    case 'stale':
      return 'Вход изменился';
    default:
      return 'Ожидаются данные';
  }
}

export function AutomationDetails({ status }: { status: DailyMlStatusDto }) {
  return (
    <details className="ml-automation" data-od-id="ranking-automation">
      <summary data-od-id="open-ranking-automation">
        <span>Работа системы</span>
        <span className="ml-automation-status">{summary(status)}</span>
      </summary>
      <div className="ml-automation-body">
        <div className="ml-automation-copy">
          <p data-od-id="inference-start-rule">{startRule(status)}</p>
          <p data-od-id="next-scheduler-check">
            Данные торговой сессии собираются после{' '}
            <span className="mono">{formatClock(status.next_check_at)}</span>. Если сессии не было,
            собирать нечего. Ранжирование ищет работу непрерывно, а считать начнёт по готовности
            данных.
          </p>
          <p>
            Ранжирование выполняется автоматически по мере готовности рыночных данных. «Проверить
            сейчас» запускает этот цикл вручную. Уже готовые результаты не пересчитываются.
          </p>
        </div>
      </div>
    </details>
  );
}
