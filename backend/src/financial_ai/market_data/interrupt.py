"""Незавершённый сбор: отдельные исходы, а не разновидность успеха.

Остановка проверяется между инструментами внутри источника (FR-044), и до этой
правки прерванный источник возвращался обычным числом записанных строк — то
есть записывался исходом «ок». Последствие видно не сразу: сессия считается
закрытой по источнику, если за неё есть успешный прогон, поэтому остановка на
третьем контракте из ста двадцати закрывала сессию навсегда. Недобранное не
попадало больше ни в один план — ни автоматический, ни ручной.

Собранное до момента остановки при этом сохраняется: исключение несёт число
записанных строк, а не отменяет запись (FR-050).
"""

from __future__ import annotations

from financial_ai.market_data.verification import WorkEvidence


class SourceStoppedError(RuntimeError):
    """Источник прерван командой остановки, не доработав до конца."""

    def __init__(
        self,
        rows_written: int = 0,
        detail: str | None = None,
        evidence: tuple[WorkEvidence, ...] = (),
    ) -> None:
        super().__init__(detail or "сбор прерван по команде")
        self.rows_written = rows_written
        self.detail = detail or "сбор прерван по команде"
        self.evidence = evidence


class SourcePartialError(RuntimeError):
    """Источник отработал не всю применимую работу, но что-то сохранил.

    Отдельный исход нужен по той же причине, что и остановка выше: без него
    частичный сбор возвращал обычное число записанных строк и записывался
    «ок». Один полученный ряд из пяти закрывал сессию всем пяти, и остальные
    четыре не попадали больше ни в один план.

    От ошибки исключение отличается тем, что **полученное уже записано** и
    удалять его нечего: незавершённой остаётся только необработанная часть.
    От остановки — тем, что причина не команда человека, а источник.

    ``unfinished`` — что именно осталось незавершённым, словами для экрана и
    журнала: «данных нет» вместо перечня превращает неизвестность в
    утверждение, которого никто не проверял (FR-032, FR-032b).
    """

    def __init__(
        self,
        rows_written: int = 0,
        detail: str | None = None,
        unfinished: tuple[str, ...] = (),
        counts_as_unavailable: bool = True,
        evidence: tuple[WorkEvidence, ...] = (),
    ) -> None:
        super().__init__(detail or "источник отработал не всю применимую работу")
        self.rows_written = rows_written
        self.unfinished = unfinished
        self.detail = detail or "источник отработал не всю применимую работу"
        self.counts_as_unavailable = counts_as_unavailable
        self.evidence = evidence
