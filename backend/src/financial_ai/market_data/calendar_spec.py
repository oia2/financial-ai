"""Объявление торгового календаря: имя, устройство и правила даты решения.

Перенесено из исследовательского репозитория (`configs/calendars/moex_daily.yaml`,
`MR-MASTER-DRO`). Там календарь — не таблица дат, а **объявленный артефакт**: у
него есть идентификатор, рынок, доска, опорная бумага, пояс и правила, по которым
дата решения превращается в дату сделки.

**Зачем это здесь.** Правила `t` и `t+1` у нас существовали и раньше, но жили в
комментариях кода и в поведении планировщика. То есть совпадение с исследованием
держалось на том, что мы их одинаково помним. При расхождении верен
исследовательский репозиторий (`AGENTS.md`), а сверять память с чужим кодом
нельзя — сверять можно только объявление с объявлением (spec 008, FR-042).

**Что отсюда следует для сбора.** Календарь обновляется первым шагом прогона, и
остальные источники собираются не дальше его последней даты (FR-043). Так
устроен и оркестратор исследования: он синхронизирует источники «до последней
даты календаря», поэтому календарь не может отстать от собранного.

Хранение дат остаётся в таблице `market_trading_session` — это разница
реализации, а не правил: там CSV, у нас PostgreSQL.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class DecisionRules:
    """Как дата решения связана с датой сделки."""

    # Снимок на дату `t` собирается ПОСЛЕ закрытия сессии `t`. Собрать раньше
    # значит завести утечку будущего в признаки.
    decision_time_reference: str = "session_close"

    # Исполнение в тот же день запрещено: модель наблюдает завершённую сессию.
    same_day_execution_allowed: bool = False

    # Сделка исполняется на открытии следующей ТОРГОВОЙ сессии, а не
    # завтрашнего календарного дня.
    execution_lag_sessions: int = 1


@dataclass(frozen=True, slots=True)
class CalendarSpec:
    """Объявление календаря целиком."""

    calendar_id: str
    calendar_type: str
    market: str
    board: str
    proxy_security: str
    timezone: str
    frequency: str
    decision: DecisionRules


# Идентификатор и состав повторяют `moex_daily_v1` исследовательского
# репозитория дословно: расхождение в любом поле означает, что мы считаем не то
# же самое, что модель, и это должно быть видно сверкой двух объявлений.
MOEX_DAILY = CalendarSpec(
    calendar_id="moex_daily_v1",
    calendar_type="trading_sessions_daily",
    market="MOEX",
    board="TQBR",
    proxy_security="SBER",
    timezone="Europe/Moscow",
    frequency="1d",
    decision=DecisionRules(),
)
