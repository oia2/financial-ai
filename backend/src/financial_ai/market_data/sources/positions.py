"""Позиции физических и юридических лиц по фьючерсам.

Самая тонкая из модальностей, и не из-за объёма кода.

**Задержанное прибытие.** Данные приходят позже закрытия сессии и годятся для
снимка на `asof_date = t`, только если успели до формирования набора. Если не
успели — они остаются наблюдением о дне `t`.

**Передатирование запрещено.** Опоздавший файл нельзя записать как наблюдение
о следующей сессии. Такая ошибка не падает тестом и не видна в данных: она
просто сдвигает историю на день, и модель обучается на смещённом сигнале.
Здесь запрет держится ещё и на сверке даты ответа с запрошенной: биржа отдаёт
последний доступный снимок, если за дату данных нет.

**Отсутствие — не ноль.** Покрытие частичное по своей природе: позиции есть не
по всем активам. Ноль означал бы «участники не держат позиций», а пропуск —
«мы не знаем». Для модели это разные утверждения.

**Пустота — не частичность.** Полное отсутствие значений записывается как
неуспех с причиной (FR-018). Прежняя реализация писала 260 строк пустых
значений на сессию и сообщала «получено 260, записано 260 (покрытие частичное —
это норма)»; формулировка верна для настоящей частичности и именно поэтому
скрыла дефект, при котором значений не было вообще: 5 непустых на 57 029.

Источник — не биржевой интерфейс данных, а форма на сайте биржи: см.
`positions_client.py`. Запись о происхождении в `PROVENANCE.md` до этой фичи
утверждала обратное.
"""

from __future__ import annotations

import datetime as dt
import logging
from collections.abc import Callable

from financial_ai.market_data.interrupt import SourcePartialError, SourceStoppedError
from financial_ai.market_data.repository import MarketDataRepository, PositionRow
from financial_ai.market_data.sources.equity_d1 import asset_id_for
from financial_ai.market_data.sources.positions_client import (
    PositionFetchKind,
    PositionFetchResult,
    PositionsClient,
    PositionsSourceError,
)

logger = logging.getLogger(__name__)

SOURCE_ID = "futures_positions"

# Сколько строк копится до закрепления. Пачка нужна, чтобы обрыв процесса не
# уносил всё собранное за сессию, и не должна быть в одну строку: каждая
# фиксация — обращение к БД, а обращений к источнику здесь и так десятки.
SAVE_BATCH_ROWS = 20


class EmptyPositionsError(RuntimeError):
    """Ни одного значения там, где источник обязан их приносить.

    Отдельный тип, а не возврат нуля: прогон должен записаться как неуспех с
    причиной, а не как успех с нулём строк (FR-018).
    """


async def sync_positions(
    client: PositionsClient,
    repository: MarketDataRepository,
    session_date: dt.date,
    sessions: list[dt.date] | None = None,
    should_stop: Callable[[], bool] | None = None,
    on_progress: Callable[[int, int], None] | None = None,
) -> int:
    """Собрать позиции за одну торговую сессию.

    Чем спрашивать — решает действующая связь бумаги: она знает, с какой даты
    контракт у бумаги есть, и не переключается между семействами молча. Второго
    соответствия, строящегося на лету, больше нет: два кода одного правила
    однажды разошлись бы, и выяснилось бы это на данных.

    Три правила аккуратности выполняются здесь, а не в клиенте, потому что все
    три требуют знания уже собранного:

    - собранная пара «инструмент — дата» повторно не запрашивается (FR-024c);
    - периоды до первой доступной даты инструмента не запрашиваются (FR-024b);
    - акция без контракта не запрашивается вовсе (FR-022).

    ``on_progress`` зовётся перед каждым ОБРАЩЕНИЕМ и считает только их:
    источник идёт минутами и десятками обращений, а на экране всё это время
    стояло одно слово «идёт» — долгий источник неотличим от зависшего
    (FR-058i).

    Счёт по списку, а не по обращениям, пробегал бы круг целиком, не спросив
    никого: собранные пары пропускаются, и после паузы это читалось бы как
    «собирает заново», хотя собранное как раз не трогается (FR-024c).
    """
    # Применимость определяется действующей связью, а не построенным на лету
    # соответствием: связь знает, С КАКОЙ ДАТЫ контракт у бумаги есть, и не
    # переключается между сериями молча (FR-017, FR-039).
    links = await repository.active_links_on(session_date)

    # Даты раньше первой связи — ручной сбор истории. Связь подтверждается с
    # той даты, когда её спросили, и никогда раньше: список серий отвечает про
    # сегодня. Без этого дополнения догон прошлого остался бы без позиций
    # навсегда, как только связи заведены ежедневным прогоном (FR-017,
    # исключение; FR-035). Ложного утверждения не возникает: интервал
    # по-прежнему говорит «подтверждено с такой-то даты», а наблюдение
    # записывает семейство, которым собрано.
    for asset_id, contract in (await repository.earliest_links_after(session_date)).items():
        links.setdefault(asset_id, contract)

    if not links:
        # Пустое соответствие — неуспех с причиной, а не успех с нулём строк
        # (FR-020): иначе сессия считалась бы собранной.
        raise EmptyPositionsError("действующих связей бумаг и контрактов нет: спрашивать нечего")

    known_tickers = await repository.tickers_with_history()
    already = await repository.positions_collected_on(session_date)
    first_seen = await repository.first_position_dates()

    # Бумага, по которой позиции собирались, обязана иметь связь — действующую
    # либо закрытую. Закрытая означает, что контракта больше нет, и это
    # объяснение: событие о закрытии человеку показано. Неуспехом остаётся
    # потеря, которую ничто не объясняет (FR-020a).
    #
    # Спрашивается это только у бумаг, торговавшихся в эту сессию. Ушедшая с
    # торгов бумага позиций не даёт по определению, и требовать у неё связи
    # значило бы ронять источник вечно: на стенде 2026-09-18 так и вышло —
    # DOMRF и FIXR с рынка ушли, а сбор по остальным 122 бумагам остановился.
    traded = await repository.assets_traded_on(session_date)
    lost: list[str] = []
    for asset_id in sorted(set(first_seen) & traded):
        if asset_id in links or await repository.link_history(asset_id):
            continue
        lost.append(asset_id)

    # Спрашиваются только бумаги, ТОРГОВАВШИЕСЯ в эту сессию. Правило уже
    # применено выше — к проверке потери связи, — но сам список обращений
    # строился по всем бумагам с историей: ушедшая с торгов бумага получала
    # обращение на каждую сессию догона, заведомо ни за чем (FR-053, FR-022).
    wanted = sorted(
        ticker
        for ticker in known_tickers
        if asset_id_for(ticker) in links and asset_id_for(ticker) in traded
    )
    if not wanted:
        if not traded:
            # Бумаг на доске в этот день нет вовсе: спрашивать некого, и это
            # не дефект соответствия.
            raise EmptyPositionsError(
                f"за {session_date} нет ни одной торговавшейся бумаги: спрашивать нечего"
            )
        raise EmptyPositionsError(
            "ни у одной торговавшейся бумаги нет фьючерсного контракта: соответствие не построилось"
        )

    pending: list[PositionRow] = []
    requested = 0
    written = 0
    skipped_collected = 0

    async def flush() -> None:
        """Закрепить накопленную пачку.

        **Границей считается commit, а не вызов `upsert`.** Незакоммиченная
        пачка живёт в памяти сессии и исчезает вместе с процессом — вместе со
        ВСЕМИ предыдущими пачками той же транзакции. Обрыв процесса после
        восьмидесяти обращений терял их все (FR-050, T207).
        """
        nonlocal pending, written
        if not pending:
            return
        written += await repository.upsert_positions(pending)
        await repository.commit()
        pending = []

    # Знаменатель — те, кого предстоит спросить, а не весь список: собранные
    # пары пропускаются, и обещать обращение к ним нельзя (FR-058i).
    todo = sum(
        (asset_id_for(ticker), links[asset_id_for(ticker)]) not in already for ticker in wanted
    )

    stopped = False
    for ticker in wanted:
        # Единица обращения здесь — инструмент, и их десятки: ждать конца
        # сессии значило бы ждать минуты после нажатия. Собранное до этого
        # момента записывается ниже (FR-044).
        if should_stop is not None and should_stop():
            logger.info("позиции за %s: сбор прерван по команде", session_date)
            stopped = True
            break

        asset_id = asset_id_for(ticker)
        contract = links[asset_id]

        if (asset_id, contract) in already:
            # Пара уже собрана. Для источников с единицей «дата» это следует из
            # правил догона; здесь единица мельче сессии, и правило нужно явно.
            #
            # Контракт входит в ключ: строка, собранная ДРУГИМ семейством, про
            # текущее не говорит ничего, и пропуск по одному активу скрывал
            # недобор нового инструмента (FR-039).
            skipped_collected += 1
            continue

        requested += 1
        if on_progress is not None:
            on_progress(requested, todo)

        try:
            fetched = await client.fetch(contract, session_date)
        except SourceStoppedError as error:
            # Если клиент сообщил остановку внутри обращения, прибавить уже
            # закреплённые пачки к числу строк исхода.
            await flush()
            raise SourceStoppedError(
                written + error.rows_written,
                error.detail,
            ) from error
        except Exception as error:
            # Полученное до ошибки или остановки закрепляется ДО выхода.
            # Иначе ошибка на восьмидесятом контракте уносила семьдесят девять
            # уже полученных ответов (FR-032a, T207).
            await flush()
            if written:
                # Обычная ошибка после успешных обращений тоже должна сообщить
                # run_source фактическое число сохранённых строк. Она остаётся
                # неуспехом, а точная причина и незавершённая пара видны в журнале.
                raise SourcePartialError(
                    rows_written=written,
                    detail=f"не удалось собрать {contract}: {error}",
                    unfinished=(f"{contract}/{session_date}",),
                ) from error
            raise
        except BaseException:
            # Например, отмена coroutine: закрепить полученное, но не менять
            # семантику системной отмены.
            await flush()
            raise

        if isinstance(fetched, PositionFetchResult):
            if fetched.kind is not PositionFetchKind.VALUE:
                continue
            snapshot = fetched.snapshot
            if snapshot is None:  # pragma: no cover - защита контракта типа
                raise PositionsSourceError("результат value не содержит снимок")
        else:
            # Тестовые клиенты переходного этапа ещё возвращают снимок/None.
            snapshot = fetched
            if snapshot is None:
                continue

        row = PositionRow(
            asset_id=asset_id,
            session_date=session_date,
            # Контракт входит в ключ наблюдения: повторный сбор той же даты
            # другим семейством не должен затирать прежнее молча (FR-039).
            contract_code=contract,
            fiz_long=snapshot.fiz_long,
            fiz_short=snapshot.fiz_short,
            jur_long=snapshot.jur_long,
            jur_short=snapshot.jur_short,
        )
        # Пустые строки не записываются вовсе: именно они заставляли догон
        # считать сессию закрытой.
        if _has_values(row):
            pending.append(row)
        if len(pending) >= SAVE_BATCH_ROWS:
            await flush()

    await flush()

    if lost:
        # Собранное записано выше: видимость расхождения не оплачивается
        # потерей данных по остальным бумагам (FR-020a).
        raise EmptyPositionsError(
            "бумаги с историей позиций потеряли связь с контрактом: "
            + ", ".join(asset_id.removeprefix("EQ_AST_") for asset_id in lost)
        )

    if stopped:
        # Прерванный сбор не судится правилом «спросили и не получили ничего»:
        # мы просто не успели спросить остальных. Но и успехом он не является:
        # исход «ок» закрывал бы сессию по этому источнику навсегда, хотя
        # спрошены были три контракта из ста двадцати (FR-050).
        raise SourceStoppedError(
            written,
            f"спрошено {requested} бумаг из {len(wanted)}",
        )

    if requested and not written:
        # Ровно то различие, ради которого FR-018 существует: настоящая
        # частичность даёт значения хотя бы по части инструментов, дефект —
        # ноль. Ноль записывается как неуспех, а не как успешная пустота.
        raise EmptyPositionsError(
            f"позиции за {session_date}: выполнено {requested} обращений, "
            "ни одного значения не получено"
        )

    logger.info(
        "позиции за %s: спрошено %d, записано %d (уже собрано %d)",
        session_date,
        requested,
        written,
        skipped_collected,
    )
    return written


# **Проверки «существовал ли инструмент тогда» здесь больше нет, и это не
# упущение.** Она пропускала обращение за датами раньше найденной поиском
# первой доступной даты, а найти её этот источник не позволяет:
#
# - список инструментов страницы от даты НЕ ЗАВИСИТ. Проверено живым обращением
#   2026-09-20: на 2025-07-01, 2026-09-04 и 2026-09-17 страница отдаёт один и
#   тот же список из 263 контрактов. Признаком применимости к дате он быть не
#   может;
# - сетка проб редкая, а пустые даты у позиций законны: контракт существует, а
#   сделок в этот день не было. Отрицательная проба отсутствия истории не
#   доказывает, и прежняя версия по одной такой пробе закрывала контракт
#   навсегда — `return not searched_for_first_date(contract)`;
# - самое раннее СОБРАННОЕ наблюдение доказывает существование с этой даты и
#   ничего не говорит про более раннее время (FR-034).
#
# Доказательства отсутствия у источника нет, поэтому нужные даты проверяются
# обращением: незнание основанием не спрашивать не является (FR-032). Поиск
# `first_available_date()` остаётся у клиента — он отвечает на вопрос аудита
# «с какой даты данные вообще есть», — но работу сбора больше не сокращает и
# из этого пути убран вместе со своими пробами.


def _has_values(row: PositionRow) -> bool:
    """Есть ли в строке хоть одно значение.

    Пустые строки не записываются вовсе: именно они заставляли догон считать
    сессию закрытой, и правильные позиции за неё не появились бы никогда.
    """
    return any(
        value is not None for value in (row.fiz_long, row.fiz_short, row.jur_long, row.jur_short)
    )


